const cat = catFile
  ? JSON.parse(fs.readFileSync(catFile, 'utf8'))
  : await fetch(`${API}/tools.json`, { signal: AbortSignal.timeout(15000) }).then(r => {
      if (!r.ok) throw new Error(`tools.json HTTP ${r.status}`);
      return r.json();
    });
