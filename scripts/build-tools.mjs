const css = fs.readFileSync(path.join(ROOT, 'src/site.css'), 'utf8') + fs.readFileSync(path.join(ROOT, 'src/form.css'), 'utf8');
const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const money = n => (Number.isInteger(Number(n)) ? String(n) : Number(n).toFixed(2));
const kitFor = slug => cat.kits.find(k => k.upgrades_from === slug && /^https:\/\//.test(k.checkout_url || ''));
const kitHref = k => `${API}/r?type=paid&slug=${encodeURIComponent(k.slug)}&to=${encodeURIComponent(k.checkout_url)}`;
const kitPrice = k => (k.launch_code ? `<s>$${money(k.price_standard)}</s>$${money(k.price_launch)} with code ${esc(k.launch_code)}` : `$${money(k.price_standard)}`);
const GENERATED = '<!-- GENERATED by scripts/build-tools.mjs from the D1 catalogue. Edit src/ and re-run npm run build-tools. -->';

