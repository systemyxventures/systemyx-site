function readPartial(slug) {
  const f = path.join(ROOT, 'src/tools', `${slug}.html`);
  if (!fs.existsSync(f)) return null;
  const raw = fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
  const m = raw.match(/^<!--meta\n([\s\S]*?)\n-->\n/);
  if (!m) throw new Error(`${slug}: partial needs a <!--meta {json} --> header`);
  return { meta: JSON.parse(m[1]), body: raw.slice(m[0].length) };
}

